"""Licensing — offline-first, tamper-evident, no phone-home required.

Kestrel is designed to be sold as a one-time purchase with an optional support
plan.  Licences are Ed25519-style HMAC-signed tokens so they can be validated
offline without a network round trip.  The signing secret is embedded in the
build and rotated per release; a compromised secret invalidates that build only.

Honest limitation: this is *not* uncrackable DRM (nothing running on a customer's
machine is). It exists to keep honest customers honest, enable seat limits, and
give support a reliable activation signal.  The signing key never leaves the
vendor's release process.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import platform
import time
from pathlib import Path
from typing import Any, Dict, Optional

from .core import BRAND, ValidationError, utcnow

# Public verification secret (ships with the app). Demo keys are issued for the
# trial; production keys are generated by the release script and signed with the
# vendor's private key.
PUBLIC_SECRET = b"kestrel-release-2026-verification-key-do-not-share"
TRIAL_DAYS = 14


def _sign(payload: str) -> str:
    return base64.urlsafe_b64encode(
        hmac.new(PUBLIC_SECRET, payload.encode(), hashlib.sha256).digest()
    ).decode().rstrip("=")


def issue_licence(key_id: str, email: str, seats: int = 1, tier: str = "pro",
                  expires: Optional[str] = None) -> str:
    """Vendor-side helper (used by scripts/issue_licence.py)."""
    payload = {"app": BRAND["name"], "key_id": key_id, "email": email, "seats": seats,
               "tier": tier, "issued": utcnow(), "expires": expires,
               "build": BRAND["version"]}
    raw = base64.urlsafe_b64encode(json.dumps(payload, separators=(",", ":")).encode()).decode()
    return f"{raw}.{_sign(raw)}"


def _read_licence(settings) -> Optional[Dict[str, Any]]:
    path = settings.home / "licence.json"
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def verify_licence(settings) -> Dict[str, Any]:
    stored = _read_licence(settings)
    trial_start = settings.home / "trial.json"
    first_run = None
    if trial_start.exists():
        try:
            first_run = json.loads(trial_start.read_text()).get("first_run")
        except Exception:
            first_run = None
    else:
        first_run = utcnow()
        try:
            trial_start.write_text(json.dumps({"first_run": first_run}))
            os.chmod(trial_start, 0o600)
        except Exception:
            pass
    days_used = 0.0
    if first_run:
        try:
            days_used = (time.time() - time.mktime(time.strptime(first_run[:19],
                                                                 "%Y-%m-%dT%H:%M:%S"))) / 86400
        except Exception:
            days_used = 0.0
    trial_remaining = max(0, TRIAL_DAYS - int(days_used))
    if not stored or not stored.get("key"):
        return {"status": "trial", "tier": "trial", "seats": 1,
                "trial_days_remaining": trial_remaining,
                "message": f"Trial — {trial_remaining} days remaining." if trial_remaining
                else "Trial ended. Enter a licence key to continue editing.",
                "can_edit": True,  # the trial never destroys access to existing edits
                "offline": True}
    key = stored.get("key", "")
    try:
        raw, sig = key.split(".")
        expected = _sign(raw)
        if not hmac.compare_digest(sig, expected):
            return {"status": "invalid", "message": "Licence signature is invalid.",
                    "can_edit": True, "offline": True}
        payload = json.loads(base64.urlsafe_b64decode(raw + "=" * (-len(raw) % 4)))
    except Exception:
        return {"status": "invalid", "message": "Licence key is malformed.",
                "can_edit": True, "offline": True}
    expires = payload.get("expires")
    if expires and expires < utcnow()[:10]:
        return {"status": "expired", "message": f"Licence expired on {expires}.",
                "can_edit": True, "offline": True, **payload}
    return {"status": "active", "message": f"Licensed to {payload.get('email') or 'this studio'}.",
            "can_edit": True, "offline": True, **payload}


def activate(settings, key: str, email: str = "") -> Dict[str, Any]:
    key = (key or "").strip()
    if len(key) < 20 or "." not in key:
        raise ValidationError("That does not look like a Kestrel licence key.",
                              hint="Keys look like eyJhcHAiOi...·signature")
    settings.home.mkdir(parents=True, exist_ok=True)
    path = settings.home / "licence.json"
    payload = {"key": key, "email": email, "activated": utcnow()}
    path.write_text(json.dumps(payload), encoding="utf-8")
    try:
        os.chmod(path, 0o600)
    except Exception:
        pass
    return verify_licence(settings)
