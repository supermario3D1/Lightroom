#!/usr/bin/env python3
"""Copy the web application and brand assets into the Python package.

The UI lives in ``web/`` during development (fast edits, no build step) and is
copied into ``src/kestrel/api/static/`` for packaging, so ``pip install`` from a
wheel serves the same files the repository ships. Running this script is part of
the release checklist; ``tests/test_packaging.py`` fails when the copies drift.
"""
from __future__ import annotations

import filecmp
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "web"
BRAND = ROOT / "assets" / "brand"
TARGET = ROOT / "src" / "kestrel" / "api" / "static"
WEB_SUFFIXES = {".html", ".css", ".js", ".svg", ".png", ".woff2", ".ico"}
BRAND_SUFFIXES = {".png", ".svg"}


def _copy_tree(source: Path, target: Path, suffixes: set[str]) -> list[Path]:
    written: list[Path] = []
    target.mkdir(parents=True, exist_ok=True)
    for path in sorted(source.iterdir()):
        if not path.is_file() or path.suffix.lower() not in suffixes:
            continue
        destination = target / path.name
        if destination.exists() and filecmp.cmp(path, destination, shallow=False):
            continue
        shutil.copy2(path, destination)
        written.append(destination)
    return written


def main() -> int:
    if not (WEB / "index.html").exists():
        print(f"error: {WEB}/index.html is missing", file=sys.stderr)
        return 2
    written = _copy_tree(WEB, TARGET, WEB_SUFFIXES)
    written += _copy_tree(BRAND, TARGET / "brand", BRAND_SUFFIXES)
    marker = TARGET / "README.txt"
    marker.write_text(
        "Generated by scripts/sync_web.py — do not edit these files here.\n"
        "The editable sources are /web and /assets/brand at the repository root.\n",
        encoding="utf-8",
    )
    print(f"synced {len(written)} file(s) into {TARGET.relative_to(ROOT)}")
    for path in written:
        print("  +", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
